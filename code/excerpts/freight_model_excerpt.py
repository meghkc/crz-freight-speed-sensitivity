"""Short excerpt of the upstream NYC freight screening model used by this analysis.

The full freight demand model (TRB 2027 freight-policy tool) is not part of this
repository. Two pieces of it define inputs to this paper, and they are copied here
verbatim so readers can see them:

1. SPEED_PROFILES: the assumed baseline operating speeds by roadway class and period
   (manuscript Methods step 3; SI Table S2). From freight_model/config.py,
   EmissionParams.speed_profiles.
2. assign_groups_fast: the whole-road random allocation to faster/unchanged/slower
   groups by cumulative-length midpoint (manuscript Methods step 5; SI S5), with its
   helpers normalized_shares, period_coverage and the group codes. From
   freight_model/analyze_aggregation_robustness_fast.py. Its docstring states it uses
   the same midpoint/cumulative-length logic as assign_groups_by_length in
   analyze_aggregation_robustness.py.

The archived allocations (phase1b/qa/paired_allocations.npz) were generated by
code/phase1b/legacy_qa.py calling assign_groups_fast with
normalized_shares(37, 46, 16) and np.random.default_rng(seed) for seeds drawn from
np.random.default_rng(20261002). legacy_qa.py and code/phase3/run_phase3.py load the
full upstream module because they also rebuild the road network from the proprietary
assignment; this file is documentation and is not imported by them.
"""
from typing import Dict

import numpy as np

# freight_model/config.py, EmissionParams.speed_profiles ({roadway_type: {period: mph}})
SPEED_PROFILES: Dict[str, Dict[str, float]] = {
    "Street": {"am_peak": 12, "midday": 18, "pm_peak": 10, "night": 25},
    "Highway": {"am_peak": 30, "midday": 45, "pm_peak": 25, "night": 55},
    "Bridge": {"am_peak": 15, "midday": 25, "pm_peak": 12, "night": 35},
    "Tunnel": {"am_peak": 10, "midday": 20, "pm_peak": 8, "night": 30},
    "Ramp": {"am_peak": 20, "midday": 30, "pm_peak": 15, "night": 40},
}

# freight_model/analyze_aggregation_robustness_fast.py
GROUP_FAST, GROUP_UNCHANGED, GROUP_SLOW = 0, 1, 2


def period_coverage(time_window: str) -> Dict[str, float]:
    if time_window == "geotab_8to18":
        return {
            "am_peak": 1.0 / 3.0,
            "midday": 1.0,
            "pm_peak": 2.0 / 3.0,
            "night": 0.0,
        }
    if time_window == "daytime_full":
        return {
            "am_peak": 1.0,
            "midday": 1.0,
            "pm_peak": 1.0,
            "night": 0.0,
        }
    if time_window == "all_day":
        return {
            "am_peak": 1.0,
            "midday": 1.0,
            "pm_peak": 1.0,
            "night": 1.0,
        }
    raise ValueError(time_window)


def normalized_shares(faster, unchanged, slower):
    total = faster + unchanged + slower
    if total <= 0:
        raise ValueError("Speed-group shares must sum to a positive number.")
    return np.array(
        [faster / total, unchanged / total, slower / total],
        dtype=float,
    )


def assign_groups_fast(lengths, shares, rng):
    """
    Exact same midpoint/cumulative-length logic as the original implementation,
    but using NumPy arrays only.
    """
    n = len(lengths)
    order = np.argsort(rng.random(n), kind="stable")
    ordered_len = lengths[order]

    total = float(ordered_len.sum())
    cut_fast = shares[0] * total
    cut_unch = (shares[0] + shares[1]) * total

    midpoint = np.cumsum(ordered_len) - 0.5 * ordered_len
    ordered_group = np.where(
        midpoint <= cut_fast,
        GROUP_FAST,
        np.where(
            midpoint <= cut_unch,
            GROUP_UNCHANGED,
            GROUP_SLOW,
        ),
    ).astype(np.int8)

    group = np.empty(n, dtype=np.int8)
    group[order] = ordered_group

    achieved = (
        np.bincount(group, weights=lengths, minlength=3) / total
    )
    return group, achieved
